// Converts drizzle-kit's generated SQL into TypeScript constants (D7).
//
// Bare React Native has no filesystem access to .sql files and no bundler
// plugin for importing them, so what ships is TypeScript. drizzle-kit still
// authors the SQL; this only changes the container.
//
// Run: npm run db:generate
import {readdirSync, readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {join} from 'node:path';

const SQL_DIR = 'drizzle';
const OUT_DIR = 'src/db/migrations';

const files = readdirSync(SQL_DIR)
  .filter(f => f.endsWith('.sql'))
  .sort();

if (files.length === 0) {
  console.error(`No .sql files in ${SQL_DIR}/. Run drizzle-kit generate first.`);
  process.exit(1);
}

mkdirSync(OUT_DIR, {recursive: true});

const entries = files.map((file, index) => {
  const name = file.replace(/\.sql$/, '');
  const statements = readFileSync(join(SQL_DIR, file), 'utf8')
    .split('--> statement-breakpoint')
    .map(s => s.trim())
    .filter(Boolean);

  const body = statements
    .map(s => '  `' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`') + '`')
    .join(',\n');

  writeFileSync(
    join(OUT_DIR, `${name}.ts`),
    '// Generated by scripts/build-migrations.mjs. Do not edit.\n' +
      `export const name = '${name}';\n` +
      `export const version = ${index + 1};\n` +
      `export const statements = [\n${body},\n] as const;\n`,
  );

  return {name, module: `./${name}`};
});

const imports = entries
  .map((e, i) => `import * as m${i + 1} from '${e.module}';`)
  .join('\n');
const list = entries.map((_, i) => `  m${i + 1}`).join(',\n');

writeFileSync(
  join(OUT_DIR, 'index.ts'),
  `// Generated by scripts/build-migrations.mjs. Do not edit.\n${imports}\n\n` +
    'export type Migration = {\n' +
    '  readonly version: number;\n' +
    '  readonly name: string;\n' +
    '  readonly statements: readonly string[];\n' +
    '};\n\n' +
    `export const migrations: readonly Migration[] = [\n${list},\n];\n`,
);

console.log(`Wrote ${entries.length} migration module(s) to ${OUT_DIR}/`);
